/**
 * 特变电工能碳数字化双中心 - 1级与2级产品类型标准定义与数据管理中心
 * 
 * 层级关系规范：
 * Level 1: 产业分类 (transformer: 变压器产业, cable: 线缆产业)
 * Level 2: 1 级产品类型 (产品大类 Major Category，编码如 1001, 1002, 200101)
 * Level 3: 2 级产品类型 (产品中类 Subcategory，10位编码如 1001010701, 2001030101)
 */

export interface ProductMajorType {
  id: string
  code: string                     // 1级大类编码 (如 1001, 1002, 200101)
  name: string                     // 1级产品类型名称 (如 变压器, 高压组合电器 GIS, 裸导线)
  industry: 'transformer' | 'cable'// 归属产业
  description: string              // 说明描述
  status: 'enabled' | 'disabled'   // 状态
  updatedAt: string                 // 维护时间
  operator: string                 // 维护人
}

export interface ProductSubType {
  id: string
  code: string                     // 10位 2级中类编码 (如 1001010701)
  name: string                     // 2级产品类型名称 (如 交流变压器-1000KV)
  majorCode: string                // 归属 1级大类编码
  majorName: string                // 归属 1级大类名称
  industry: 'transformer' | 'cable'// 归属产业
  unit: string                     // 标准计量单位 (万kVA, 台, 间隔, 支, 面, 吨, 万m, km)
  description?: string             // 规格/技术说明
  status: 'enabled' | 'disabled'   // 状态
  updatedAt: string                 // 维护时间
  operator: string                 // 维护人
}

